def runs(par, text, base, bold):
    for i, seg in enumerate(re.split(r'\*\*', text)):
        if seg: par.add_run(seg, char_pr_id_ref=(bold if i % 2 else base))

def para(text='', base='a', bold='ab'):
    p = doc.add_paragraph('', include_run=False)
    if text: runs(p, text, st[base], st[bold])
    return p

def table(head, rows, widths_mm):
    t = doc.add_table(len(rows) + 1, len(head), width=W)
    t.set_column_widths([int(w * MM) for w in widths_mm])
    for r, row in enumerate([head] + rows):
        for c, txt in enumerate(row):
            cell = t.cell(r, c); cell.set_text('')
            lines = str(txt).split('\n')
            for k, ln in enumerate(lines):
                p = cell.paragraphs[0] if k == 0 else cell.add_paragraph('')
                if r == 0: p.add_run(ln, char_pr_id_ref=st['th'])
                elif ln.startswith('⚠'): p.add_run(ln, char_pr_id_ref=st['warn'])
                else: runs(p, ln, st['td'], st['tdb'])
            if r == 0:
                try: t.set_cell_shading(r, c, '#E8EEF7')
                except Exception: pass
    doc.add_paragraph('')

